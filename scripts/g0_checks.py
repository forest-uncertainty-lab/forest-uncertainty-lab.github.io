"""G0-01 and G0-04 from the FIRMS VIIRS Suomi NPP yearly archive for Indonesia. Writes reports/g0/.

G0-04 profiles every yearly file from --first-year to the last mask year (2013-2025 is about
260 MB, downloaded into --archive-dir). G0-01 compares the 11 provinces over the mask years
with the committed masks, using the archive files in data/raw that the masks were built from.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict
from datetime import datetime, timezone
from pathlib import Path

import geopandas as gpd
import pandas as pd

from sulteng.assign import assign
from sulteng.config import ROOT, load_params
from sulteng.fetch import download, save_manifest
from sulteng.firms import read_archive
from sulteng.history import field_changes, province_years, raw_profile
from sulteng.masks import categorize, masks_from_json, within_years
from sulteng.publish import read_json

OUT = ROOT / "reports" / "g0"


def fetch_years(params, years, archive_dir: Path) -> dict[int, dict]:
    manifest = read_json(archive_dir / "manifest.json")
    for year in years:
        name = f"viirs-snpp_{year}_Indonesia.csv"
        if name not in manifest or not (archive_dir / name).exists():
            print(f"downloading {name}", flush=True)
            manifest[name] = asdict(download(params.archive_url_for(year), archive_dir / name))
            save_manifest(archive_dir / "manifest.json", manifest)
    return {y: manifest[f"viirs-snpp_{y}_Indonesia.csv"] for y in years}


def archive_report(params, years, archive_dir: Path) -> str:
    entries = fetch_years(params, years, archive_dir)
    profiles = {y: raw_profile(archive_dir / entries[y]["file"], y) for y in years}
    cutoff = params.masks.archive_min_last_modified
    lines = [
        f"# G0-04: the VIIRS archive year by year, {years[0]}–{years[-1]}",
        "",
        f"Generated by `scripts/g0_checks.py` on {datetime.now(timezone.utc):%Y-%m-%d}. Source: FIRMS VIIRS Suomi NPP",
        f"yearly files for Indonesia (`{params.archive_url}`). Dates are UTC, as FIRMS cuts the files.",
        "A day without detections anywhere in Indonesia is a likely data gap, not a day without fires.",
        f"Files dated before {cutoff} may carry the faulty fire-type codes fixed in May 2025.",
        "",
        "| Year | Rows | File date | Months without rows | Days without rows | Longest run without rows | `version` | `type` values |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for y in years:
        p, e = profiles[y], entries[y]
        gap, start = p["longest_gap"]
        run = f"{gap} days from {start}" if gap else "none"
        lines.append(
            f"| {y} | {p['rows']:,} | {(e['last_modified'] or 'unknown')[:10]} | {', '.join(p['empty_months']) or 'none'} | "
            f"{p['days_without_rows']} | {run} | {', '.join(p['values'].get('version', {})) or 'missing'} | "
            f"{', '.join(f'{k}: {v:,}' for k, v in p['values'].get('type', {}).items()) or 'missing'} |"
        )
    notes = field_changes(profiles)
    lines += ["", "## Changes between years", ""]
    lines += [f"- {n}" for n in notes] if notes else ["None: every year has the same columns and the same values in the fields checked "
                                                      f"({', '.join(sorted(profiles[years[0]]['values']))})."]
    lines += ["", "## Rows per month", "",
              "| Year | " + " | ".join(f"{m:02d}" for m in range(1, 13)) + " |",
              "|---|" + "---|" * 12]
    for y in years:
        lines.append(f"| {y} | " + " | ".join(f"{n:,}" for n in profiles[y]["rows_per_month"].values()) + " |")
    (OUT / "g0-04-profiles.json").write_text(json.dumps(profiles, indent=1), encoding="utf-8")
    return "\n".join(lines) + "\n"


def province_report(params) -> tuple[str, pd.DataFrame]:
    years = list(params.masks.archive_years)
    raw = ROOT / "data" / "raw"
    archive = within_years(pd.concat(
        [read_archive(raw / f"viirs-snpp_{y}_Indonesia.csv", utc_offset_hours=params.utc_offset_hours) for y in years],
        ignore_index=True,
    ), years)
    provinces = gpd.read_file(ROOT / "data" / "boundaries" / "provinces.geojson")
    districts = gpd.read_file(ROOT / "data" / "boundaries" / "districts.geojson")
    masks = masks_from_json(json.loads((ROOT / "data" / "public" / "masks.json").read_text(encoding="utf-8")))
    table = province_years(categorize(assign(archive, provinces, districts), masks), provinces, years)

    total = table.groupby(["province", "island", "area_km2"], as_index=False)[
        ["volcano", "static_suspect", "other", "all"]].sum()
    total["other_rate"] = total["other"] / len(years) / total["area_km2"] * 1000
    total["flagged_share"] = (total["static_suspect"] + total["volcano"]) / total["all"].where(total["all"] > 0)
    total = total.sort_values("other_rate", ascending=False)
    by_year = table.pivot(index="province", columns="year", values="other_per_1000_km2")

    span = f"{years[0]}–{years[-1]}"
    lines = [
        f"# G0-01: the 11 provinces on one basis, {span}",
        "",
        f"Generated by `scripts/g0_checks.py` on {datetime.now(timezone.utc):%Y-%m-%d}.",
        "",
        "- Sensor: VIIRS on Suomi NPP only, from the FIRMS yearly archive (the same files the masks were built from).",
        f"- Years: every WITA day of {', '.join(map(str, years))}; no year or season left out.",
        "- Denominator: land area of each province (geoBoundaries ADM1, equal-area projection EPSG:6933).",
        "- Detections at suspected static sources and volcanoes are counted separately, using the committed masks.",
        "  \"Other\" detections are what remains: possible vegetation or land fires, none of them confirmed.",
        "",
        f"## Other detections per 1,000 km² of land per year, {span} average",
        "",
        "| Province | Island | Land km² | " + " | ".join(f"Other {y}" for y in years)
        + " | Rate | Static or volcano share |",
        "|---|---|---|" + "---|" * len(years) + "---|---|",
    ]
    counts = table.pivot(index="province", columns="year", values="other")
    for r in total.itertuples(index=False):
        name = f"**{r.province}**" if r.province == params.focus_province else r.province
        share = "–" if pd.isna(r.flagged_share) else f"{r.flagged_share:.0%}"
        lines.append(f"| {name} | {r.island} | {r.area_km2:,.0f} | "
                     + " | ".join(f"{counts.loc[r.province, y]:,}" for y in years)
                     + f" | {r.other_rate:.1f} | {share} |")
    lines += ["", "## The same rate, year by year", "",
              "| Province | " + " | ".join(map(str, years)) + " |", "|---|" + "---|" * len(years)]
    for province in total["province"]:
        name = f"**{province}**" if province == params.focus_province else province
        lines.append(f"| {name} | " + " | ".join(f"{by_year.loc[province, y]:.1f}" for y in years) + " |")
    lines += ["", f"Full table with every count: `g0-01-provinces.csv`."]
    return "\n".join(lines) + "\n", table


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive-dir", type=Path, default=ROOT / "data" / "raw",
                        help="where the yearly files for G0-04 are kept (about 260 MB)")
    parser.add_argument("--first-year", type=int, default=2013)
    args = parser.parse_args()
    params = load_params()
    OUT.mkdir(parents=True, exist_ok=True)

    text, table = province_report(params)
    (OUT / "g0-01-provinces.md").write_text(text, encoding="utf-8")
    table.round(4).to_csv(OUT / "g0-01-provinces.csv", index=False)
    print("wrote g0-01", flush=True)

    years = list(range(args.first_year, max(params.masks.archive_years) + 1))
    args.archive_dir.mkdir(parents=True, exist_ok=True)
    (OUT / "g0-04-archive.md").write_text(archive_report(params, years, args.archive_dir), encoding="utf-8")
    print("wrote g0-04", flush=True)


if __name__ == "__main__":
    main()
